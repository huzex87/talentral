// The Contents field is refreshed by Word on open; build.js also pre-fills entries so
// viewers that never refresh fields (Google Docs, phone previews) still show them.
function contents() {
  md.push('## Contents', '', '<!--TOC-->', '');
  return [
    new Paragraph({ spacing: { before: 120, after: 200 }, children: [new TextRun({ text: 'Contents', bold: true, size: 32, color: C.ink })] }),
    new TableOfContents('Contents', { hyperlink: true, headingStyleRange: '1-1' }),
    pageBreak(),
  ];
}

